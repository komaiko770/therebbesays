const fmtInt = n => new Intl.NumberFormat('en-US').format(Math.round(Number(n) || 0));
const fmtUsd = n => `$${(Number(n) || 0).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
const fmtDay = iso => new Intl.DateTimeFormat('en-US', { month: 'short', day: 'numeric' }).format(new Date(`${iso}T00:00:00`));

// Build a continuous daily series so gaps render as zero bars.
function densify(rows, valueKey, days) {
  const map = new Map(rows.map(r => [String(r.day).slice(0, 10), Number(r[valueKey]) || 0]));
  const out = [];
  const today = new Date();
  for (let i = days - 1; i >= 0; i--) {
    const d = new Date(today);
    d.setDate(today.getDate() - i);
    const iso = d.toISOString().slice(0, 10);
    out.push({ day: iso, value: map.get(iso) || 0 });
  }
  return out;
}

function barChart(container, series, { color = '#c9a349', format = fmtInt } = {}) {
  if (!container) return;
  if (!series.length || series.every(p => !p.value)) {
    container.innerHTML = '<p class="empty-note">No data in this range yet.</p>';
    return;
  }
  const W = 960, H = 220, padL = 44, padR = 12, padT = 14, padB = 26;
  const innerW = W - padL - padR, innerH = H - padT - padB;
  const max = Math.max(...series.map(p => p.value), 1);
  const n = series.length;
  const gap = n > 60 ? 1 : 3;
  const bw = Math.max(1, (innerW / n) - gap);
  const ticks = 4;
  const gridLines = Array.from({ length: ticks + 1 }, (_, i) => {
    const v = (max / ticks) * i;
    const y = padT + innerH - (v / max) * innerH;
    return `<line x1="${padL}" y1="${y}" x2="${W - padR}" y2="${y}" stroke="rgba(201,163,73,.12)" stroke-width="1"/><text x="${padL - 6}" y="${y + 3}" text-anchor="end">${format(v)}</text>`;
  }).join('');
  const labelEvery = Math.ceil(n / 8);
  const bars = series.map((p, i) => {
    const h = (p.value / max) * innerH;
    const x = padL + i * (bw + gap);
    const y = padT + innerH - h;
    const showLabel = i % labelEvery === 0 || i === n - 1;
    return `<rect class="bar" x="${x.toFixed(1)}" y="${y.toFixed(1)}" width="${bw.toFixed(1)}" height="${Math.max(0, h).toFixed(1)}" rx="${Math.min(2, bw / 2)}" fill="${color}"><title>${fmtDay(p.day)}: ${format(p.value)}</title></rect>${showLabel ? `<text x="${(x + bw / 2).toFixed(1)}" y="${H - 8}" text-anchor="middle">${fmtDay(p.day)}</text>` : ''}`;
  }).join('');
  container.innerHTML = `<svg viewBox="0 0 ${W} ${H}" preserveAspectRatio="xMidYMid meet" role="img">${gridLines}${bars}</svg>`;
}

function renderKpis(totals) {
  const kpis = document.querySelector('#kpis');
  const cards = [
    { label: 'New questions', value: fmtInt(totals.questions), sub: `in the last ${rangeDays} days` },
    { label: 'Est. research cost', value: fmtUsd(totals.cost_usd), sub: 'logged pipeline spend' },
    { label: 'Input tokens', value: fmtInt(totals.input_tokens), sub: 'sent to the model' },
    { label: 'Output tokens', value: fmtInt(totals.output_tokens), sub: 'generated by the model' },
    { label: 'Web searches', value: fmtInt(totals.web_searches), sub: 'source lookups' },
  ];
  kpis.innerHTML = cards.map(c => `<div class="kpi"><div class="k-label">${c.label}</div><div class="k-value">${c.value}</div><div class="k-sub">${c.sub}</div></div>`).join('');
}

async function loadStats() {
  try {
    const { data, error } = await supabase.rpc('admin_daily_stats', { p_days: rangeDays });
    if (error) throw error;
    const stats = typeof data === 'string' ? JSON.parse(data) : data;
    renderKpis(stats.totals || {});
    barChart(document.querySelector('#chart-questions'), densify(stats.questions_daily || [], 'count', rangeDays), { color: '#c9a349', format: fmtInt });
    barChart(document.querySelector('#chart-cost'), densify(stats.usage_daily || [], 'cost_usd', rangeDays), { color: '#8bbf74', format: fmtUsd });
    const tokenSeries = densify(stats.usage_daily || [], 'input_tokens', rangeDays).map((p, i) => {
      const out = (stats.usage_daily || []).find(r => String(r.day).slice(0, 10) === p.day);
      return { day: p.day, value: p.value + (Number(out?.output_tokens) || 0) };
    });
    barChart(document.querySelector('#chart-tokens'), tokenSeries, { color: '#7fa8d0', format: fmtInt });
    document.querySelector('#foot').textContent = `Generated ${new Date(stats.generated_at).toLocaleString('en-US')}`;
  } catch (error) {
    if ((error.message || '').toLowerCase().includes('not authorized')) {
      showGate({ title: 'Not an admin account', lede: 'This signed-in account does not have admin access. Sign in with an authorized account.', allowSignin: false });
    } else {
      document.querySelector('#foot').textContent = `Could not load analytics: ${error.message}`;
    }
  }
}

async function route(session) {
  ready = true;
  if (!session) {
    showGate({ title: 'Admin sign-in', lede: 'Sign in with an authorized admin account to view analytics.', allowSignin: true });
    return;
  }
  const { data, error } = await supabase.rpc('is_admin');
  if (error || data !== true) {
    showGate({ title: 'Not an admin account', lede: `Signed in as ${session.user.email || 'this account'}, which is not an admin. Sign out and use an authorized account.`, allowSignin: false });
    return;
  }
  hide(gate);
  show(dashboard);
  await loadStats();
}

document.querySelector('[data-google]')?.addEventListener('click', async () => {
  setStatus('Redirecting to Google…', 'info');
  const { error } = await supabase.auth.signInWithOAuth({ provider: 'google', options: { redirectTo: `${location.origin}/admin` } });
  if (error) setStatus(error.message, 'error');
});
document.querySelector('[data-email]')?.addEventListener('submit', async event => {
  event.preventDefault();
  const email = event.target.elements.email.value.trim();
  if (!email) return;
  setStatus('Sending your sign-in link…', 'info');
  const { error } = await supabase.auth.signInWithOtp({ email, options: { emailRedirectTo: `${location.origin}/admin` } });
  setStatus(error ? error.message : 'Check your inbox for a one-time sign-in link.', error ? 'error' : 'success');
});
document.querySelectorAll('[data-signout]').forEach(btn => btn.addEventListener('click', () => supabase.auth.signOut()));
document.querySelector('[data-range]')?.addEventListener('click', event => {
  const btn = event.target.closest('[data-days]');
  if (!btn) return;
  rangeDays = Number(btn.dataset.days) || 30;
  document.querySelectorAll('[data-range] button').forEach(b => b.classList.toggle('active', b === btn));
  loadStats();
});

supabase.auth.getSession().then(({ data }) => route(data.session));
supabase.auth.onAuthStateChange((_event, session) => { if (ready) route(session); });
